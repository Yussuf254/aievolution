              <h2><span class="sec-num">Chapter 11</span>Encounter with British Colonialism</h2>
              <p>When the British colonial administration extended its authority over Kenya and Uganda, it encountered a landscape of independent kingdoms and chiefdoms governed by indigenous rulers. The Wanga Empire, then under Nabongo Mumia, was merely one such autonomous polity; prior to European arrival, these groups did not recognise Wanga hegemony.</p>
              <p>The Europeans entered Namwonja''s territory during his reign. A ruler of discernment, he elected not to resist the imposition of British colonial rule, recognising that the British possessed vastly superior armaments and that armed confrontation would result in the decimation of his young fighting men.</p>
              <h3>The Colonial Reconfiguration of Territory</h3>
              <p>The Kavirondo Gulf — a minor depression at the north-eastern corner of Lake Nyanza — was renamed Winam by the colonial authorities. The administration subsequently established Kavirondo District, encompassing the Western and Nyanza regions, and bifurcated it into North and Central Kavirondo. Mumia was elevated to Paramount Chief (King) of North Kavirondo District, to which Namwonja''s kingdom was subordinated.</p>
              <p>Initially, Mumia appointed local chiefs to serve as his headmen. However, in 1912, the colonial administration amalgamated Bunyala, Bukhekhe, Busonga, and Samia into a single Samia Location. Mumia appointed his brother, Kadima, as headman of this new location in 1912, and promoted him to area chief in 1913. Consequently, all local chiefs, including King Namwonja, were reduced to the status of Kadima''s headmen.</p>
            </section>

