              <p>
                Under colonial administration, Namwonja was demoted to the status of a mere headman.
                Nevertheless, the British permitted him to retain his position as traditional king concurrently,
                thereby allowing him to hold both traditional and colonial portfolios.
              </p>
              <p>
                In 1918, Headmen Namwonja Mukudi and Ngira Ng''ayo were both demoted and supplanted by their
                respective sons — Mukudi and Omala — as headmen of Bunyala South and Bunyala North. The
                proximate cause of Namwonja''s demotion was his refusal to travel to Mumias to attend meetings
                with Mumia and the Wanga agent, Kadima. This refusal likely stemmed from Namwonja''s
                self-perception as a sovereign equal to Mumia, rendering the summons of a fellow king
                intolerable to his dignity.
              </p>
