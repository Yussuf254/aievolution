              <p>
                The Kavirondo Gulf — a minor depression at the north-eastern corner of Lake Nyanza — was
                renamed Winam by the colonial authorities. The administration subsequently established
                Kavirondo District, encompassing the Western and Nyanza regions, and bifurcated it into
                North and Central Kavirondo. Mumia was elevated to Paramount Chief (King) of North Kavirondo
                District, to which Namwonja''s kingdom was subordinated.
              </p>
              <p>
                Initially, Mumia appointed local chiefs to serve as his headmen. However, in 1912, the
                colonial administration amalgamated Bunyala, Bukhekhe, Busonga, and Samia into a single
                Samia Location. Mumia appointed his brother, Kadima, as headman of this new location in 1912,
                and promoted him to area chief in 1913. Consequently, all local chiefs, including King
                Namwonja, were reduced to the status of Kadima''s headmen.
              </p>
